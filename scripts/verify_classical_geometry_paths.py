#!/usr/bin/env python3
"""Frozen Pool A paths and valid-zero measurement audit; no GT access."""
import sys,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT/'scripts'))
import numpy as np,yaml
from run_classical_v4 import ReadGuard,verify,verify_selection,write


def main():
    cfg=yaml.safe_load((ROOT/'configs/classical_v4_v1.yaml').read_text());out=Path(cfg['output']);p=verify(cfg,out);verify_selection(out)
    if (out/'path_and_mask_validation.json').exists():print('Path and mask audit complete; no repeat');return
    with ReadGuard(cfg,out,'calibrate',p['calibration_cases']):
        with np.load(Path(cfg['dataset'])/'geometry/train_geometry.npz') as a:g={k:a[k] for k in a.files}
        valid=g['valid_ray'];origins=g['station_origin_m'][:,None,None,:];d=g['ray_direction']
        near=origins+d*g['t_near'][...,None];far=origins+d*g['t_far'][...,None]
        endpoints=np.concatenate([near[valid],far[valid]])
        bounds_error=max(float(np.maximum(-endpoints,0).max()),float(np.maximum(endpoints-.6,0).max()))
        length_error=float(abs(g['path_length_m'][valid]-(g['t_far'][valid]-g['t_near'][valid])).max())
        norm_error=float(abs(np.linalg.norm(d[valid],axis=-1)-1).max())
        assert bounds_error<1e-10 and length_error<1e-10 and norm_error<1e-10
        record=p['calibration_cases'][0];y=np.load(Path(cfg['dataset'])/record['train_projection_path'],mmap_mode='r')
        valid_zero=int(((y==0)&valid).sum());invalid_nonzero=int(((y!=0)&~valid).sum())
        assert invalid_nonzero==0
        result=dict(Pool_A_valid_ray_count=int(valid.sum()),ray_unit_norm_max_error=norm_error,near_far_domain_bound_max_error_m=bounds_error,path_length_vs_far_minus_near_max_error_m=length_error,
                    measurement_case=record['case_id'],valid_zero_measurements=valid_zero,invalid_nonzero_measurements=invalid_nonzero,padding='Only real unique station IDs enter solver; no padded views generated by classical workflow',
                    valid_zero_exclusion=False,GT_opened=False,GT128_PoolB_test_opened=False)
        write(out/'path_and_mask_validation.json',result);print(result)
if __name__=='__main__':main()
